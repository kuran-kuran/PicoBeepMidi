// Knob value 5 in the emulator's 1..10 range maps to 113, not 128.
inline void configure_cmu(Cmu800Tone& tone, unsigned channel)
{
    tone.initialize();
    tone.set_wave(channel == 1 ? Cmu800Tone::wave_type::bass : Cmu800Tone::wave_type::melody);
    tone.set_decay(113);
    tone.enable_sustain(channel != 1);
    tone.set_sustain(channel == 0 ? 113 : 0);
}
